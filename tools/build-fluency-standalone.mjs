#!/usr/bin/env node
/* ── Build: standalone AI Fluency Track export ──────────────────────
   Bundles fluency.html and everything it depends on into a single
   self-contained HTML file (export/ai-fluency-track.html) that can be
   hosted anywhere — or opened straight from disk — with no other files.

   What it does:
     1. Reads the lesson ids from FL_TRACK inside fluency.html.
     2. Evaluates the shared data files (js/data.js, js/slides-*.js,
        js/visuals.js) and filters them down to just those lessons.
     3. Inlines the three stylesheets, js/slide-utils.js, js/tts.js,
        the filtered data, the Haileybury logo (base64) and the favicon.
     4. Strips the bits that only make sense on the full site: the
        Back / Portfolio / share-link buttons, the index.html CTA,
        the PWA manifest and the service-worker registration.

   Run:  node tools/build-fluency-standalone.mjs
   The transforms are anchored to exact strings in fluency.html and
   fail loudly if the page changes shape — fix the anchor, re-run. */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

/* Evaluate a browser data file and return one of its top-level
   bindings. `expr` is appended so const/var both work. */
function evalGlobal(file, expr) {
  return vm.runInNewContext(read(file) + '\n;(' + expr + ')', {}, { filename: file });
}

/* JSON that is safe to embed inside a <script> element. */
function embedJSON(value) {
  return JSON.stringify(value).replace(/<\//g, '<\\/');
}

/* Replace an exact anchor once; throw if it isn't found so a changed
   fluency.html can't silently produce a broken export. */
function replaceOnce(html, anchor, replacement, label) {
  if (!html.includes(anchor)) throw new Error('Anchor not found (' + label + '): ' + anchor.slice(0, 80));
  return html.replace(anchor, replacement);
}

let html = read('fluency.html');

/* ── 1. Lesson ids, straight from the page ── */
const flTrackMatch = html.match(/var FL_TRACK = \[[\s\S]*?\];/);
if (!flTrackMatch) throw new Error('FL_TRACK not found in fluency.html');
const FL_IDS = vm.runInNewContext(flTrackMatch[0] + ';FL_TRACK', {}).map((t) => t.id);
const idSet = new Set(FL_IDS);

/* ── 2. Filter shared data to the fluency lessons ── */
const UNITS = evalGlobal('js/data.js', 'UNITS')
  .map((u) => ({ ...u, lessons: u.lessons.filter((l) => idSet.has(l.id)) }))
  .filter((u) => u.lessons.length);

const slideFiles = [
  ['js/slides-u1u2.js', 'SLIDES_U1U2'],
  ['js/slides-u3u4.js', 'SLIDES_U3U4'],
  ['js/slides-u5u6.js', 'SLIDES_U5U6'],
  ['js/slides-critical.js', 'SLIDES_CRITICAL'],
  ['js/slides-advanced.js', 'SLIDES_ADVANCED'],
  ['js/slides-gcse.js', 'SLIDES_GCSE'],
];
const slideVars = slideFiles.map(([file, name]) => {
  const all = evalGlobal(file, name);
  const subset = {};
  for (const id of Object.keys(all)) if (idSet.has(Number(id))) subset[id] = all[id];
  return [name, subset];
});

const coveredIds = new Set(slideVars.flatMap(([, s]) => Object.keys(s).map(Number)));
const missing = FL_IDS.filter((id) => !coveredIds.has(id));
if (missing.length) throw new Error('No slide deck for lesson id(s): ' + missing.join(', '));

const ALL_VISUALS = evalGlobal('js/visuals.js', 'SLIDE_VISUALS');
const SLIDE_VISUALS = {};
for (const key of Object.keys(ALL_VISUALS)) {
  if (idSet.has(Number(key.split(':')[0]))) SLIDE_VISUALS[key] = ALL_VISUALS[key];
}

/* ── 3. Inline assets ── */
const logoURI = 'data:image/png;base64,' +
  readFileSync(join(ROOT, 'assets/brand/logo/haileybury-magenta.png')).toString('base64');
const iconURI = 'data:image/svg+xml;base64,' + Buffer.from(read('icon.svg')).toString('base64');

const dataScript =
  '<script>\n/* Course content — filtered to the ' + FL_IDS.length + ' AI Fluency Track lessons.\n' +
  '   Generated from js/data.js, js/slides-*.js and js/visuals.js. */\n' +
  'var UNITS = ' + embedJSON(UNITS) + ';\n' +
  slideVars.map(([name, s]) => 'var ' + name + ' = ' + embedJSON(s) + ';').join('\n') + '\n' +
  'var SLIDE_VISUALS = ' + embedJSON(SLIDE_VISUALS) + ';\n</script>';

/* ── 4. Page transforms ── */

// Generated-file banner
html = replaceOnce(html, '<!DOCTYPE html>',
  '<!DOCTYPE html>\n<!-- AI Fluency Track — standalone export.\n     Generated by tools/build-fluency-standalone.mjs from fluency.html;\n     do not edit by hand — edit the source files and re-run the build. -->',
  'banner');

// PWA manifest gone; favicon inlined
html = replaceOnce(html, '  <link rel="manifest" href="manifest.json">\n', '', 'manifest');
html = replaceOnce(html, '<link rel="icon" href="icon.svg" type="image/svg+xml">',
  '<link rel="icon" href="' + iconURI + '" type="image/svg+xml">', 'favicon');

// Stylesheets → inline <style> blocks (same order)
for (const css of ['css/style.css', 'css/lesson.css', 'css/brand.css', 'css/labs.css', 'css/wow.css']) {
  html = replaceOnce(html, '<link rel="stylesheet" href="' + css + '">',
    '<style>\n/* ── inlined: ' + css + ' ── */\n' + read(css) + '\n</style>', css);
}

// Header: drop the Back button and Portfolio link (site-internal pages),
// inline the logo
html = replaceOnce(html,
  '      <button class="fl-back" onclick="window.location.href=\'index.html\'">← Back</button>\n', '', 'back button');
html = replaceOnce(html,
  '      <a class="btn btn-ghost btn-sm" href="portfolio.html?t=fluency" style="margin-left:10px" title="Your notes, exit tickets and progress — save as PDF">📄 Portfolio</a>\n', '', 'portfolio link');
html = replaceOnce(html, 'src="assets/brand/logo/haileybury-magenta.png"', 'src="' + logoURI + '"', 'logo');

// Cert share button builds a verify.html URL that won't exist standalone
html = replaceOnce(html,
  '      <button class="fl-print-btn" id="flShareBtn" onclick="flShareCredential()" style="margin-left:8px;background:var(--bg-card);color:var(--track-primary);border:1.5px solid var(--track-primary)">🔗 Copy share link</button>\n', '', 'share button');

// Scope panel: the full-course CTA points at index.html
html = replaceOnce(html,
  '        <a class="fl-scope-cta" href="index.html">Browse the full 59-lesson course →</a>\n', '', 'course CTA');

// Offline banner copy: there is no service worker here, but the page is
// fully self-contained, so the honest claim is simpler
html = replaceOnce(html, 'You are offline — all 24 lessons are available from cache',
  'You are offline — this page is self-contained, keep learning', 'offline copy');

// Script tags → inlined sources + filtered data
html = replaceOnce(html,
  '  <!-- Scripts — same data + slide files as full course -->\n' +
  '  <script src="js/slide-utils.js"></script>\n' +
  '  <script src="js/data.js"></script>\n' +
  '  <script src="js/slides-u1u2.js"></script>\n' +
  '  <script src="js/slides-u3u4.js"></script>\n' +
  '  <script src="js/slides-u5u6.js"></script>\n' +
  '  <script src="js/slides-critical.js"></script>\n' +
  '  <script src="js/slides-advanced.js"></script>\n' +
  '  <script src="js/slides-gcse.js"></script>\n' +
  '  <script src="js/quiz-bank.js"></script>\n' +
  '  <script src="js/visuals.js"></script>\n' +
  '  <script src="js/labs.js"></script>',
  '  <!-- Inlined scripts — slide helpers + course content + interactive labs -->\n' +
  '  <script>\n/* ── inlined: js/slide-utils.js ── */\n' + read('js/slide-utils.js') + '\n</script>\n' +
  '  ' + dataScript + '\n' +
  '  <script>\n/* ── inlined: js/labs.js ── */\n' + read('js/labs.js') + '\n</script>',
  'script block');

// No service worker in the standalone bundle
html = replaceOnce(html,
  "\n  if ('serviceWorker' in navigator) {\n    navigator.serviceWorker.register('sw.js').catch(function(){});\n  }\n", '\n', 'service worker');

// tts.js → inline (self-attaching; the modal exists by this point)
html = replaceOnce(html, '<script src="js/tts.js" defer></script>',
  '<script>\n/* ── inlined: js/tts.js ── */\n' + read('js/tts.js') + '\n</script>', 'tts');

/* ── 5. Write + sanity checks ── */
mkdirSync(join(ROOT, 'export'), { recursive: true });
const out = join(ROOT, 'export', 'ai-fluency-track.html');
writeFileSync(out, html);

if (/src="(js|css)\//.test(html) || /href="css\//.test(html)) throw new Error('Export still references local js/ or css/ files');
for (const id of FL_IDS) {
  if (!html.includes('"' + id + '":[')) throw new Error('Lesson ' + id + ' deck missing from export');
}

console.log('Wrote export/ai-fluency-track.html (' + (html.length / 1024 / 1024).toFixed(2) + ' MB)');
console.log('Lessons bundled: ' + FL_IDS.join(', '));
console.log('Visuals bundled: ' + Object.keys(SLIDE_VISUALS).length);
